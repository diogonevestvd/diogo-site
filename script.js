function bootActiveNavigation() {
  const currentFile = (window.location.pathname.split("/").pop() || "index.html").toLowerCase();
  document.querySelectorAll(".side-nav a, .mobile-nav a").forEach((link) => {
    const linkFile = (link.getAttribute("href") || "").split("/").pop().toLowerCase();
    const isActive = linkFile === currentFile || (currentFile === "" && linkFile === "index.html");
    link.classList.toggle("active", isActive);
    if (isActive) {
      link.setAttribute("aria-current", "page");
    } else {
      link.removeAttribute("aria-current");
    }
  });
}

function bootScrollProgress() {
  if (document.querySelector(".scroll-progress")) return;

  const progress = document.createElement("div");
  progress.className = "scroll-progress";
  progress.setAttribute("aria-hidden", "true");
  progress.innerHTML = "<span></span>";
  document.body.appendChild(progress);

  const bar = progress.querySelector("span");
  let ticking = false;

  const update = () => {
    const doc = document.documentElement;
    const max = Math.max(1, doc.scrollHeight - window.innerHeight);
    const value = Math.min(1, Math.max(0, window.scrollY / max));
    bar.style.transform = `scaleX(${value})`;
    progress.classList.toggle("is-visible", window.scrollY > 6);
    document.body.classList.toggle("is-scrolled", window.scrollY > 10);
    ticking = false;
  };

  const requestUpdate = () => {
    if (!ticking) {
      window.requestAnimationFrame(update);
      ticking = true;
    }
  };

  update();
  window.addEventListener("scroll", requestUpdate, { passive: true });
  window.addEventListener("resize", requestUpdate);
}

function bootTopbarBehavior() {
  const topbar = document.querySelector(".mobile-topbar");
  if (!topbar) return;

  let lastY = window.scrollY;
  let ticking = false;

  const update = () => {
    const currentY = window.scrollY;
    const goingDown = currentY > lastY + 8;
    const goingUp = currentY < lastY - 8;

    if (currentY > 170 && goingDown) {
      document.body.classList.add("is-topbar-hidden");
    }

    if (goingUp || currentY < 48) {
      document.body.classList.remove("is-topbar-hidden");
    }

    lastY = currentY;
    ticking = false;
  };

  window.addEventListener("scroll", () => {
    if (!ticking) {
      window.requestAnimationFrame(update);
      ticking = true;
    }
  }, { passive: true });
}

