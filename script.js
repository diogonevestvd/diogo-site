const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const hasGsap = typeof window.gsap !== "undefined";
const hasScrollTrigger = hasGsap && typeof window.ScrollTrigger !== "undefined";

if (hasScrollTrigger) {
  gsap.registerPlugin(ScrollTrigger);
}

function getCurrentLanguage() {
  return localStorage.getItem("siteLanguage") || "pt";
}

function resetSplitState(element) {
  element.removeAttribute("aria-label");
  delete element.dataset.splitReady;
}

function applyLanguage(lang) {
  const dict = translations[lang] || translations.pt;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) {
      el.textContent = dict[key];
      resetSplitState(el);
    }
  });

  document.querySelectorAll("[data-lang-option]").forEach((el) => {
    el.classList.toggle("is-active", el.dataset.langOption === lang);
  });

  localStorage.setItem("siteLanguage", lang);
}

function splitWords(element) {
  if (prefersReducedMotion || element.dataset.splitReady === "true") return [];

  const original = element.textContent.replace(/\s+/g, " ").trim();
  if (!original) return [];

  element.dataset.splitReady = "true";
  element.setAttribute("aria-label", original);
  element.innerHTML = "";

  const parts = original.split(" ");
  const words = [];

  parts.forEach((word, index) => {
    const wrapper = document.createElement("span");
    wrapper.className = "split-word";
    wrapper.setAttribute("aria-hidden", "true");

    const inner = document.createElement("span");
    inner.textContent = word;
    wrapper.appendChild(inner);
    element.appendChild(wrapper);
    words.push(inner);

    if (index < parts.length - 1) {
      element.appendChild(document.createTextNode(" "));
    }
  });

  return words;
}

function prepareTextReveals() {
  const textTargets = document.querySelectorAll([
    "h1",
    ".section-title",
    ".subheading",
    ".project-snippet h3",
    ".project-card h3",
    ".feature-project-title",
    ".portfolio-kicker",
    ".project-metrics strong",
    ".info-card h2",
    ".hero-thesis",
    ".hero-signature span",
    ".hero-proof-grid strong",
    ".photo-caption span",
    ".eyebrow",
    ".lead"
  ].join(","));

  textTargets.forEach((element) => {
    if (element.closest(".mobile-menu-overlay") || element.closest(".sidebar")) return;
    element.classList.add("text-reveal");
    const words = splitWords(element);

    if (prefersReducedMotion) {
      element.classList.add("is-visible");
      return;
    }

    if (hasGsap && words.length) {
      gsap.set(words, { yPercent: 118, rotate: 5, opacity: 0 });
      gsap.to(words, {
        yPercent: 0,
        rotate: 0,
        opacity: 1,
        duration: 0.95,
        ease: "power4.out",
        stagger: 0.035,
        scrollTrigger: hasScrollTrigger ? {
          trigger: element,
          start: "top 88%",
          once: true
        } : undefined
      });
    }
  });
}

function prepareRevealItems() {
  const items = document.querySelectorAll([
    ".liquid-panel",
    ".liquid-soft",
    ".skill-pill",
    ".language-row",
    ".text-link",
    ".button-row .liquid-button",
    ".hero-index",
    ".hero-signature span",
    ".hero-proof-grid > div",
    ".photo-caption"
  ].join(","));

  items.forEach((item, index) => {
    if (item.closest(".sidebar") || item.closest(".mobile-menu-overlay")) return;
    item.classList.add("reveal-item");

    if (prefersReducedMotion) {
      item.classList.add("is-visible");
      return;
    }

    if (hasGsap) {
      gsap.set(item, { y: 34, opacity: 0, filter: "blur(10px)" });
      gsap.to(item, {
        y: 0,
        opacity: 1,
        filter: "blur(0px)",
        duration: 0.9,
        delay: Math.min(index * 0.018, 0.16),
        ease: "power3.out",
        scrollTrigger: hasScrollTrigger ? {
          trigger: item,
          start: "top 92%",
          once: true
        } : undefined
      });
    }
  });

  if (!hasGsap) {
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.16 });

    document.querySelectorAll(".reveal-item, .text-reveal").forEach((item) => observer.observe(item));
  }
}

function wrapNavigationText() {
  const links = document.querySelectorAll(".side-nav a, .mobile-nav a");
  links.forEach((link) => {
    const label = link.textContent.replace(/\s+/g, " ").trim();
    if (!label) return;
    link.setAttribute("aria-label", label);
    link.innerHTML = "";

    const labelSpan = document.createElement("span");
    labelSpan.className = "nav-label";
    labelSpan.dataset.label = label;
    labelSpan.setAttribute("aria-hidden", "true");

    [...label].forEach((char, index) => {
      const charSpan = document.createElement("span");
      charSpan.textContent = char === " " ? "\u00A0" : char;
      charSpan.style.setProperty("--char-index", index);
      labelSpan.appendChild(charSpan);
    });

    link.appendChild(labelSpan);
  });
}

function bootSmoothScroll() {
  if (prefersReducedMotion || typeof window.Lenis === "undefined") return;

  const lenis = new Lenis({
    duration: 1.08,
    smoothWheel: true,
    wheelMultiplier: 0.92,
    touchMultiplier: 1.25
  });

  if (hasScrollTrigger) {
    lenis.on("scroll", ScrollTrigger.update);
  }

  function raf(time) {
    lenis.raf(time);
    requestAnimationFrame(raf);
  }

  requestAnimationFrame(raf);
}

function bootPageTransition() {
  const transition = document.querySelector(".page-transition");
  if (!transition) return;

  transition.style.animation = "none";
  const bands = transition.querySelectorAll(".transition-band");
  const word = transition.querySelector(".transition-word");

  if (prefersReducedMotion || !hasGsap) {
    transition.classList.add("is-hidden");
    return;
  }

  gsap.set(transition, { pointerEvents: "auto" });
  gsap.set(bands, { yPercent: 0 });
  gsap.set(word, { y: 0, opacity: 1 });

  const loadTimeline = gsap.timeline({
    defaults: { ease: "power4.inOut" },
    onComplete: () => transition.classList.add("is-hidden")
  });

  loadTimeline
    .to(word, { y: -20, opacity: 0, duration: 0.42, ease: "power2.in" }, 0.18)
    .to(bands, {
      yPercent: -105,
      duration: 1.05,
      stagger: 0.08
    }, 0.25)
    .set(transition, { pointerEvents: "none" });

  document.querySelectorAll("a[href]").forEach((link) => {
    const href = link.getAttribute("href");
    if (!href || href.startsWith("#") || href.startsWith("mailto:") || href.startsWith("tel:")) return;
    if (link.target === "_blank" || link.hasAttribute("download")) return;

    const destination = new URL(href, window.location.href);
    if (destination.origin !== window.location.origin) return;
    if (destination.pathname === window.location.pathname && destination.hash === window.location.hash) return;

    link.addEventListener("click", (event) => {
      event.preventDefault();
      transition.classList.remove("is-hidden");
      gsap.killTweensOf([bands, word]);
      gsap.set(transition, { pointerEvents: "auto" });
      gsap.set(bands, { yPercent: 105 });
      gsap.set(word, { y: 22, opacity: 0 });

      gsap.timeline({ defaults: { ease: "power4.inOut" } })
        .to(bands, { yPercent: 0, duration: 0.74, stagger: 0.055 }, 0)
        .to(word, { y: 0, opacity: 1, duration: 0.42, ease: "power2.out" }, 0.28)
        .add(() => {
          window.location.href = destination.href;
        }, ">-0.02");
    });
  });
}

function bootMenu() {
  const menuToggle = document.querySelector(".menu-toggle");
  const menuClose = document.querySelector(".menu-close");
  const mobileOverlay = document.querySelector(".mobile-menu-overlay");
  const panel = document.querySelector(".mobile-menu-panel");
  const navItems = document.querySelectorAll(".mobile-nav a");
  let lastFocusedElement = null;

  if (!menuToggle || !mobileOverlay || !panel) return;

  const openMenu = () => {
    lastFocusedElement = document.activeElement;
    mobileOverlay.hidden = false;
    mobileOverlay.classList.add("is-open");
    menuToggle.classList.add("is-menu-open");
    menuToggle.setAttribute("aria-expanded", "true");
    document.body.classList.add("menu-lock");
    document.body.classList.remove("is-topbar-hidden");

    if (!prefersReducedMotion && hasGsap) {
      gsap.killTweensOf([mobileOverlay, panel, navItems]);
      gsap.set(mobileOverlay, { autoAlpha: 1 });
      gsap.fromTo(panel,
        { yPercent: -10, scale: 0.96, clipPath: "inset(0 0 100% 0 round 28px)" },
        { yPercent: 0, scale: 1, clipPath: "inset(0 0 0% 0 round 28px)", duration: 0.78, ease: "power4.out" }
      );
      gsap.fromTo(navItems,
        { y: 32, opacity: 0, rotate: 2 },
        { y: 0, opacity: 1, rotate: 0, duration: 0.72, stagger: 0.06, ease: "power4.out", delay: 0.12 }
      );
      gsap.delayedCall(0.18, () => (menuClose || navItems[0] || panel).focus());
    } else {
      window.requestAnimationFrame(() => (menuClose || navItems[0] || panel).focus());
    }
  };

  const closeMenu = () => {
    menuToggle.classList.remove("is-menu-open");
    menuToggle.setAttribute("aria-expanded", "false");
    document.body.classList.remove("menu-lock");

    if (!prefersReducedMotion && hasGsap) {
      gsap.timeline({
        defaults: { ease: "power3.inOut" },
        onComplete: () => {
          mobileOverlay.classList.remove("is-open");
          mobileOverlay.hidden = true;
          if (lastFocusedElement && typeof lastFocusedElement.focus === "function") lastFocusedElement.focus();
        }
      })
        .to(navItems, { y: -16, opacity: 0, duration: 0.22, stagger: 0.025 }, 0)
        .to(panel, { yPercent: -4, scale: 0.98, clipPath: "inset(0 0 100% 0 round 28px)", duration: 0.48 }, 0.05)
        .to(mobileOverlay, { autoAlpha: 0, duration: 0.28 }, 0.2);
    } else {
      mobileOverlay.classList.remove("is-open");
      mobileOverlay.hidden = true;
      if (lastFocusedElement && typeof lastFocusedElement.focus === "function") lastFocusedElement.focus();
    }
  };

  menuToggle.addEventListener("click", openMenu);
  if (menuClose) menuClose.addEventListener("click", closeMenu);

  mobileOverlay.addEventListener("click", (event) => {
    if (event.target === mobileOverlay) closeMenu();
  });

  document.addEventListener("keydown", (event) => {
    const isOpen = mobileOverlay.classList.contains("is-open");
    if (event.key === "Escape" && isOpen) closeMenu();
    if (event.key !== "Tab" || !isOpen) return;

    const focusable = [...panel.querySelectorAll('a[href], button:not([disabled]), [tabindex]:not([tabindex="-1"])')];
    if (!focusable.length) return;

    const first = focusable[0];
    const last = focusable[focusable.length - 1];

    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  });
}

function bootMagneticHover() {
  if (prefersReducedMotion || !hasGsap || window.matchMedia("(hover: none)").matches) return;

  const targets = document.querySelectorAll(".liquid-button, .side-nav a, .mobile-nav a, .lang-pill, .text-link");

  targets.forEach((target) => {
    target.addEventListener("mousemove", (event) => {
      const rect = target.getBoundingClientRect();
      const x = event.clientX - rect.left - rect.width / 2;
      const y = event.clientY - rect.top - rect.height / 2;
      gsap.to(target, { x: x * 0.12, y: y * 0.20, duration: 0.42, ease: "power3.out" });
    });

    target.addEventListener("mouseleave", () => {
      gsap.to(target, { x: 0, y: 0, duration: 0.62, ease: "elastic.out(1, 0.42)" });
    });
  });
}

